"""Build the cuRobo robot configuration for UR5e + RG2.

Sources, all under the integration repo:
    URDF   ros2_ws/src/robot_description/urdf/ur5e_ros.urdf  (arm + RG2, tcp link)
    XRDF   config/robot/ur5e.xrdf                            (arm collision spheres,
                                                              generated by Isaac's
                                                              Robot Description Editor)
    RG2    config/robot/rg2_collision_spheres.yaml           (TODO(mohammad) values)

cuRobo v0.7.8 reads XRDF through curobo.util.xrdf_utils.convert_xrdf_to_curobo.
The RG2 spheres are merged into the converted config; an empty RG2 file makes
load_robot_config raise, so the backend never plans with an unmodelled gripper.

The URDF uses package:// mesh URIs. cuRobo only needs meshes for
visualization, so meshes are not loaded (collision is sphere-based).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

RG2_LINKS = (
    "onrobot_rg2_base_link",
    "onrobot_rg2_left_outer_knuckle",
    "onrobot_rg2_left_inner_knuckle",
    "onrobot_rg2_left_inner_finger",
    "onrobot_rg2_right_outer_knuckle",
    "onrobot_rg2_right_inner_knuckle",
    "onrobot_rg2_right_inner_finger",
)


def load_rg2_spheres(path: Path) -> dict[str, list[dict[str, Any]]]:
    """Return {link: [{center, radius}, ...]}; raise if any RG2 link is empty."""
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    spheres = data.get("spheres", {}) or {}
    missing = [link for link in RG2_LINKS if not spheres.get(link)]
    if missing:
        raise RuntimeError(
            "RG2 collision spheres are not filled in for: "
            + ", ".join(missing)
            + f" (see {path}; TODO(mohammad))"
        )
    out: dict[str, list[dict[str, Any]]] = {}
    for link in RG2_LINKS:
        entries = []
        for item in spheres[link]:
            center = [float(v) for v in item["center"]]
            if len(center) != 3:
                raise ValueError(f"{path}: {link}: center must have 3 values")
            entries.append({"center": center, "radius": float(item["radius"])})
        out[link] = entries
    return out


def merge_spheres(robot_cfg: dict[str, Any], extra: dict[str, list[dict[str, Any]]]) -> dict[str, Any]:
    """Add link spheres to a cuRobo robot config dict (in place) and return it."""
    kin = robot_cfg.setdefault("robot_cfg", robot_cfg).get("kinematics", robot_cfg.get("kinematics"))
    if kin is None:
        raise ValueError("robot config has no kinematics section")
    spheres = kin.get("collision_spheres")
    if isinstance(spheres, str):
        raise ValueError("collision_spheres is a file reference; expected an inline mapping after XRDF conversion")
    if spheres is None:
        spheres = kin["collision_spheres"] = {}
    for link, entries in extra.items():
        spheres[link] = [dict(e) for e in entries]
    link_names = kin.setdefault("collision_link_names", [])
    for link in extra:
        if link not in link_names:
            link_names.append(link)
    return robot_cfg


def load_robot_config(urdf_path: Path, xrdf_path: Path, rg2_spheres_path: Path, base_link: str, ee_link: str) -> dict[str, Any]:
    """Convert the XRDF with cuRobo and merge the RG2 spheres. Imports cuRobo lazily."""
    from curobo.util.xrdf_utils import convert_xrdf_to_curobo  # type: ignore

    for p in (urdf_path, xrdf_path, rg2_spheres_path):
        if not p.is_file():
            raise FileNotFoundError(p)
    robot_cfg = convert_xrdf_to_curobo(str(urdf_path), str(xrdf_path), None)
    kin = robot_cfg["robot_cfg"]["kinematics"] if "robot_cfg" in robot_cfg else robot_cfg["kinematics"]
    kin["base_link"] = base_link
    kin["ee_link"] = ee_link
    kin["load_meshes"] = False
    return merge_spheres(robot_cfg, load_rg2_spheres(rg2_spheres_path))
