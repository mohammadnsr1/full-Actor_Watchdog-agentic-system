#!/usr/bin/env python3
"""Split model_registry.yaml into the two role-specific part files.

    python3 tools/split_registry.py            # writes config/parts/*.yaml

config/parts/watchdog_parts.yaml  (WatchDog only)
    object ids, kind, TF frames, enabled flag, the features (placement, hole,
    reorient frames) that belong to each part, tolerances, and limits split
    into limits.sim (the registry's values, Isaac units) and limits.hardware
    (TODO(mohammad), newtons). No collision geometry, no grasp data.

config/parts/executor_parts.yaml  (executor only)
    object ids, kind, TF frames, enabled flag, collision geometry, grasp data
    and the ACM pairs. No tolerances, no limits: the executor does not learn
    what WatchDog judges against.

Nothing is invented: every number is copied from the registry; hardware
limits are left as TODO. Feature ownership is read off the frame ids
(`<part>_placement`, `<part>_hole`, `<part>_reorient`), which is how the
registry names them.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "ros2_ws" / "src" / "robot_backend" / "config" / "model_registry.yaml"
OUT_DIR = ROOT / "config" / "parts"
FEATURE_SUFFIXES = ("placement", "hole", "reorient")

WATCHDOG_HEADER = """# WatchDog-only part data, generated by tools/split_registry.py from
# ros2_ws/src/robot_backend/config/model_registry.yaml. Do not edit by hand;
# edit the registry and regenerate. limits.sim are the registry values (Isaac
# effort units); limits.hardware are TODO(mohammad) in newtons.
"""
EXECUTOR_HEADER = """# Executor-only part data, generated by tools/split_registry.py from
# ros2_ws/src/robot_backend/config/model_registry.yaml. Do not edit by hand.
# Carries geometry and grasp data only; no tolerances or limits.
"""


def main() -> int:
    with REGISTRY.open("r", encoding="utf-8") as handle:
        registry = yaml.safe_load(handle)
    objects = registry.get("objects", {})

    features_by_part: dict[str, dict[str, str]] = {}
    for oid, entry in objects.items():
        if entry.get("kind") != "frame":
            continue
        for suffix in FEATURE_SUFFIXES:
            tail = f"_{suffix}"
            if oid.endswith(tail):
                part = oid[: -len(tail)]
                features_by_part.setdefault(part, {})[suffix] = oid

    watchdog: dict = {"source_registry": str(REGISTRY.relative_to(ROOT)), "parts": {}, "frames": {}}
    executor: dict = {
        "source_registry": str(REGISTRY.relative_to(ROOT)),
        "parts": {},
        "frames": {},
        "acm_allowed_object_pairs": registry.get("acm_allowed_object_pairs", []),
    }
    for oid, entry in objects.items():
        base = {
            "kind": entry.get("kind", "object"),
            "enabled": bool(entry.get("enabled", True)),
            "tf_frame": entry.get("tf_frame"),
            "lookup_frame": entry.get("lookup_frame"),
        }
        if entry.get("kind") == "frame":
            watchdog["frames"][oid] = dict(base)
            executor["frames"][oid] = dict(base)
            continue
        spec = entry.get("spec") or {}
        w = dict(base)
        w["features"] = features_by_part.get(oid, {})
        if spec.get("tolerances"):
            w["tolerances"] = dict(spec["tolerances"])
        if spec.get("limits"):
            w["limits"] = {
                "sim": dict(spec["limits"]),
                "hardware": {k: None for k in spec["limits"]},  # TODO(mohammad): newtons
            }
        watchdog["parts"][oid] = w
        e = dict(base)
        for key in ("class_name", "graspable", "source", "collision"):
            if key in entry:
                e[key] = entry[key]
        if spec.get("grasp"):
            e["grasp"] = dict(spec["grasp"])
        executor["parts"][oid] = e

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "watchdog_parts.yaml").write_text(
        WATCHDOG_HEADER + yaml.safe_dump(watchdog, sort_keys=False, default_flow_style=False), encoding="utf-8"
    )
    (OUT_DIR / "executor_parts.yaml").write_text(
        EXECUTOR_HEADER + yaml.safe_dump(executor, sort_keys=False, default_flow_style=False), encoding="utf-8"
    )
    print(f"wrote {OUT_DIR / 'watchdog_parts.yaml'} ({len(watchdog['parts'])} parts, {len(watchdog['frames'])} frames)")
    print(f"wrote {OUT_DIR / 'executor_parts.yaml'} ({len(executor['parts'])} parts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
