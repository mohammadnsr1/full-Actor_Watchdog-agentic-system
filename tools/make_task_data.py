#!/usr/bin/env python3
"""Write this cell's task data in the labmate's record shapes (EB2): task_data/.

    python3 tools/make_task_data.py            # (re)write task_data/
    python3 tools/make_task_data.py --check    # exit 1 if task_data/ is not what the config gives

The authoring agent of the executor baseline reads a task-data tree like the
labmate's (`benchmark/prompts/docs/task-data.md`): `tasks/<id>/task.yaml`,
`environments/<name>/declaration.yaml`, `robots/<name>/composite.yaml`, and
`assemblies/<name>/`. The first three are generated here from the cell's own
config, so every name keeps one home:

    config/platforms/sim.yaml                 topics, frames, joints, actions, services, home pose
    config/cameras/sim.yaml                   camera1 (wrist) topics and optical frame
    config/layouts/fmb_assembly_2/nominal.yaml starting poses, jitter ranges, base1 static
    config/requirements/fmb_assembly_2.yaml   acceptance parts, fixtures, interchangeable groups
    config/parts/watchdog_parts.yaml          the checker's per-part bands (the agent is told the band,
                                              as the labmate's task.yaml states its tolerances)
    assets/usd/fmb1/binding.json              occurrence -> prim, prim <- object frame
    benchmark/assemblies/fmb1/                the assembly graph (mates) it points at
    ros2_ws/src/isaac_trajectory_bridge/config/rg2_calibration_table.csv   RG2 width domain

`assemblies/fmb1/` is not copied here: EB4 stages it from `benchmark/` into
the agent's /data view next to this tree. Records are a SUBSET of the labmate's
schemas (each says `subset_of`): names are written out in full, because this
cell's ROS names carry no robot token, and the control surface is this cell's
(planning service + FollowJointTrajectory + RG2 controller), not theirs.
Nothing WatchDog-only goes in (no placement file, no requirements text, no limits).
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "task_data"
TASK_ID = "fmb_assembly_2"
ASSEMBLY = "fmb1"
ENVIRONMENT = "ur5e_rg2_vention_cell"
ROBOT = "ur5e_rg2_cell"
HEADER = "# Generated by tools/make_task_data.py from this cell's config; do not edit by hand.\n"


def _load(rel: str) -> dict:
    return yaml.safe_load((REPO / rel).read_text()) or {}


class _NoAliases(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def _dump(data: dict) -> str:
    return HEADER + yaml.dump(data, Dumper=_NoAliases, sort_keys=False, default_flow_style=None, width=110)


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _rg2_width_domain() -> list[float]:
    path = REPO / "ros2_ws/src/isaac_trajectory_bridge/config/rg2_calibration_table.csv"
    widths = [float(r["true_width_m"]) for r in csv.DictReader(path.open()) if r.get("direction", "open_to_close") == "open_to_close"]
    return [round(min(widths), 6), round(max(widths), 6)]


