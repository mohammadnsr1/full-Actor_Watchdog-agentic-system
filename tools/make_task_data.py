    g = plat["gripper"]
    return {
        "schema": "droidstack.robot-composite/1",
        "subset_of": "droidstack.robot-composite/1 (benchmark/prompts/docs/robot.md section 8); names in full, no token",
        "name": ROBOT,
        "robot": "UR5e (simulated; UR7e on the hardware platform) with an OnRobot RG2",
        "mount": {"parent_frame": plat["frames"]["world"], "child_frame": plat["frames"]["base"]},
        "frames": {"world": plat["frames"]["world"], "base": plat["frames"]["base"], "flange": "wrist_3_link",
                   "tcp": plat["frames"]["tcp"],
                   "tcp_note": "fixed frame on the gripper (URDF); the grasp centre moves along its +Z with jaw width"},
        "joints": {"arm": list(plat["joints"]["arm"]), "gripper": plat["joints"]["gripper_master"],
                   "gripper_note": "the RG2's one actuated joint; the other finger joints mimic it"},
        "home_joint_positions": dict(plat["scene"]["home_joint_positions"]),
        "controllers": {
            "arm": {"type": "control_msgs/action/FollowJointTrajectory", "action": plat["motion"]["action"],
                    "cancel_service": plat["motion"]["cancel_service"],
                    "goal_tolerance_rad": plat["motion"]["goal_tolerance_rad"],
                    "publish_rate_hz": plat["motion"]["publish_rate_hz"]},
            "planning": {"service_namespace": plat["services"]["planning_namespace"],
                         "group": plat["motion"]["planning_group"],
                         "note": "plan only (MoveIt now, cuRobo later); it never moves the arm"},
            "gripper": {"services": dict(g["services"]), "guarded_move_action": g["action"]["guarded_move"]},
        },
        "gripper": {
            "class": "parallel_jaw",
            "model": "OnRobot RG2",
            "structure": "four-bar linkage: the fingertips stay parallel and travel along the TCP's +Z as they close",
            "width_domain_m": _rg2_width_domain(),
            "tcp_to_grasp_center": {
                "source": "ros2_ws/src/isaac_trajectory_bridge/config/rg2_calibration_table.csv",
                "function": "robot_backend.utils.rg2_geometry.tcp_target_from_grasp_center(center, width_m)",
                "summary_m": {"closed": 0.0685, "open": 0.025},
                "note": "calibrated per width; use the function, never a straight line between the ends",
            },
            "readings": dict(g["readings"]),
            "force_model": "guarded close: stops at a force threshold or an effort plateau; the stop reason is the grip proxy",
        },
        "measured_state": {"joint_states": plat["topics"]["joint_states"], "declared_rate_hz": plat["motion"]["publish_rate_hz"]},
    }


